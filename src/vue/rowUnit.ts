/**
 * 基准行的**窗口高度抬升**。
 *
 * ## 为什么需要
 *
 * `E.rowHeight()` 只按**容器宽**给 64/60/56/52/48 五档，与窗口高度无关。实测
 * （2026-10-08，出厂 5 张卡、`docs/ARCHITECTURE.md` §12.10 有原始表）：
 *
 * | 视口 | 可用高 | 版面高 | 行轨 | 卡片高 | 版面占比 |
 * |---|---|---|---|---|---|
 * | 1408×768 | 684 | 464 | 64px | 224px | 68% |
 * | 1408×900 | 816 | 464 | 64px | 224px | 57% |
 * | 1408×1440 | 1356 | 464 | 64px | 224px | **34%** |
 *
 * 也就是：**同样的版面在八个视口下像素尺寸完全一样**（卡宽倒是 562→776 在变）——
 * 宽度是响应式的，高度不是。13″ 笔记本上刚好的格子，搬到 27″ 上就是屏幕上方
 * 一小撮卡加一大片空白。网格类产品（iOS 小组件、GridStack）都会让基准单元随屏幕缩放。
 *
 * ## 两条不能碰的线
 *
 * **① 倍率不能依赖"行数"。** 若 `rowPx` 反比于行数（即"把可用高度摊给现有几行"），
 * 收紧掉两行就会让每行变高、总高不变，「收紧看不出效果」原样回来 ——
 * 那正是 `docs/ARCHITECTURE.md` §10.10 否掉 `1fr` 的原因。所以倍率**只是
 * (容器宽, 窗口高) 的函数**，不含行数；收紧行数就必然让版面变矮，这条性质得以保住。
 *
 * **② 不能无上限。** 行高一旦随窗口高度线性跑下去，4K 竖屏会得到一张 300px 高的
 * "一行"；卡片内容靠 `cqh` 连续缩放（`GridLayout.vue` 的 `container-type: size` 就是
 * 为此而设），于是正文会一路涨成海报。故封顶。
 *
 * ## 参考高取 684 的来历
 *
 * 应用自己的默认窗口是 **1280×800 逻辑像素**，那扇窗的 `.stage` 可用高实测 **684**
 * （视口高 − 84 的壳：状态条 + 内边距 + 页脚）。取它当参考点意味着：
 * **出厂默认窗口及更小的窗口里倍率恒为 1，已经调好的观感一个像素都不动**；
 * 只有比默认窗口更大的窗口才放大。换参考点等于把"默认窗口"这个锚挪走，
 * 会让笔记本上看到的格子也跟着变，没必要。
 *
 * 封顶 2 倍：格子最大长到 128px（宽档 64 × 2），正文大约 13px → 24px。
 * 再往上就不是"大屏上看得清"，而是"大屏上只剩几行字"。
 */

/** 参考可用高：默认窗口 1280×800 下 `.stage` 的实测高 */
export const ROW_UNIT_REF_H = 684

/** 倍率上限。见文件头「② 不能无上限」 */
export const ROW_UNIT_MAX_SCALE = 2

/**
 * 窗口高度 → 行高倍率。恒 ≥1（比参考窗更矮的窗口不缩格子 —— 那会掉到字号下限那条红线）。
 *
 * `stageH` 在挂载前是 0（`useElementSize` 的初值），此时返回 1，
 * 于是首屏按引擎原值渲染，不会有"先大后小"的跳变。
 * 非有限值（NaN / Infinity，例如容器被 `display:none` 时量到 0）一并当 0 处理。
 */
export function rowUnitScale(stageH: number): number {
  if (!Number.isFinite(stageH) || stageH <= ROW_UNIT_REF_H) return 1
  return Math.min(ROW_UNIT_MAX_SCALE, stageH / ROW_UNIT_REF_H)
}

/**
 * 把引擎给的宽档基准行高，按窗口高度抬升成实际行高。
 *
 * 取整是有意的：行轨落在整数像素上，卡片高度才不会被累计的小数拖出
 * 半像素（`tests/e2e/layout.spec.ts` 那条"卡片高 = span 个行轨 + 间距"
 * 的断言容差只有 1.5px，而 12 行的小数误差能到 6px）。
 */
export function rowUnitPx(base: number, stageH: number): number {
  if (!Number.isFinite(base) || base <= 0) return base
  return Math.round(base * rowUnitScale(stageH))
}
